#!/usr/bin/env python3
"""Calibration audit of the published WorkflowEvals runs (evals.typesafe.ai).

Writes results/RESULTS.md and results/*.csv. Downloads about 23 MB from Hugging Face on first run.
No model is called; everything is computed from the published per-question probabilities.
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import numpy as np

from calaudit.data import DATASETS, load
from calaudit.metrics import brier_binary, coverage_at, ece, reliability, split_conformal_selective, top_tie_share

OUT = Path(__file__).resolve().parent / "results"
KINDS = ("noul", "choice")  # categorical questions; score questions are reported separately


TARGETS = (0.95, 0.98)


def summarize(answers, reference="consensus", splits=200, delta=0.1):
    c = np.array([a.confidence for a in answers])
    y = np.array([a.agrees(reference) for a in answers])
    groups = np.array([f"{a.workflow}/{a.case_id}" for a in answers])
    row = {
        "n": len(answers),
        "agreement": y.mean(),
        "mean_confidence": c.mean(),
        "overconfidence": c.mean() - y.mean(),
        "ece": ece(c, y),
        "brier": brier_binary(c, y),
        "top_tie_share": top_tie_share(c),
        "answer_not_top": sum(a.confidence < a.top_probability for a in answers),
    }
    for t in TARGETS:
        k = int(round(100 * t))
        row[f"oracle_cov_{k}"] = coverage_at(c, y, t)
        if splits:
            s = split_conformal_selective(groups, c, y, alpha=1 - t, delta=delta, splits=splits)
            row[f"ltt_cov_{k}"] = s["coverage_mean"]
            row[f"ltt_cov_{k}_p10"] = s["coverage_p10"]
            row[f"ltt_cov_{k}_p90"] = s["coverage_p90"]
            row[f"ltt_agreement_{k}"] = s["agreement_mean"]
            row[f"ltt_violation_{k}"] = s["violation_rate"]
    return row


def case_gate(wf, model, kinds=("noul", "choice", "score")):
    """Per case: the lowest confidence among the model's answered questions, and whether the case is right."""
    lowest = {}
    for a in wf.answers:
        if a.model == model and a.kind in kinds:
            lowest[a.case_id] = min(lowest.get(a.case_id, 1.0), a.confidence)
    ids = sorted(case for (m, case) in wf.case_correct if m == model)
    gate = np.array([lowest.get(i, 0.0) for i in ids])  # a case with no answered question is escalated
    ok = np.array([wf.case_correct[(model, i)] for i in ids])
    return np.array(ids), gate, ok


def fmt(v, pct=True):
    if isinstance(v, (int, np.integer)):
        return str(v)
    if v != v:
        return "n/a"
    return f"{100 * v:.1f}%" if pct else f"{v:.3f}"


def table(rows, cols, header):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        lines.append("| " + " | ".join(c(r) if callable(c) else str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def write_csv(path, rows):
    if not rows:
        return
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--splits", type=int, default=200, help="random calibration/test splits for LTT")
    p.add_argument("--quick", action="store_true", help="20 splits, for a fast smoke run")
    args = p.parse_args(argv)
    splits = 20 if args.quick else args.splits
    OUT.mkdir(exist_ok=True)

    workflows = {name: load(name) for name in DATASETS}
    md = ["# Results", "", f"Generated by `run_all.py` with {splits} calibration/test splits.", ""]

    # 0. Sanity: recomputed exact action-set agreement equals the published score for every run.
    md += ["## 0. Reproduction check", "",
           "Exact action-set agreement with the consensus reference, recomputed from the published decisions,"
           " versus the score in each dataset's `dataset.json`.", ""]
    rows = []
    for name, wf in workflows.items():
        for model in sorted(wf.published_accuracy):
            rows.append({"workflow": name, "model": model, "published": wf.published_accuracy[model],
                         "recomputed": wf.recomputed_accuracy[model],
                         "match": abs(wf.published_accuracy[model] - wf.recomputed_accuracy[model]) < 1e-12})
    write_csv(OUT / "reproduction.csv", rows)
    md += [f"{sum(r['match'] for r in rows)} of {len(rows)} runs match exactly (see `reproduction.csv`).", ""]
    md += ["Questions that could not be matched to a reference question (different state or definition):", ""]
    md += [table([{"workflow": n, "detail": ", ".join(f"{m} {k}" for m, k in sorted(wf.unmatched.items())) or "none"}
                  for n, wf in workflows.items()], ["workflow", "detail"], ["workflow", "unmatched per model"]), ""]

    all_answers = [a for wf in workflows.values() for a in wf.answers if a.kind in KINDS]
    models = sorted({a.model for a in all_answers})

    # 1. Pooled question-level calibration and selective agreement.
    by_model = defaultdict(list)
    for a in all_answers:
        by_model[a.model].append(a)
    pooled = [{"model": m, **summarize(by_model[m], splits=splits)} for m in models]
    write_csv(OUT / "pooled.csv", pooled)
    md += ["## 1. Question-level calibration, all four workflows pooled", "",
           "Yes/no and choice questions. Agreement = the model's answer equals the consensus reference answer"
           " (mean of the OpenAI and Anthropic reference probabilities). Confidence = probability the model put"
           " on its own answer. Each model is scored on the questions its own workflow path asked.", "",
           "`top tie` is the share of all answers sitting on one identical confidence value >= 0.99 (usually"
           " exactly 1.0). A threshold cannot split a tie, so a large tie whose agreement is below the target"
           " makes that target unreachable.", ""]
    md += [table(sorted(pooled, key=lambda r: r["ece"]),
                 ["model", "n", lambda r: fmt(r["agreement"]), lambda r: fmt(r["mean_confidence"]),
                  lambda r: f"{100 * r['overconfidence']:+.1f} pts", lambda r: fmt(r["ece"], False),
                  lambda r: fmt(r["brier"], False), lambda r: fmt(r["top_tie_share"]), "answer_not_top"],
                 ["model", "questions", "agreement", "mean conf.", "conf. minus agreement", "ECE", "Brier",
                  "top tie", "answer below top prob."]), ""]
    md += ["### Selective agreement: how many questions can be auto-accepted at a target agreement", "",
           "`oracle` is the largest share of questions, most confident first, whose agreement stays at or above"
           " the target (in-sample, no guarantee). `LTT` picks the threshold on a random half of the cases with"
           " Learn-then-Test (delta 0.1, exact binomial test, Bonferroni over a 101-point grid from 0.50 to"
           " 1.00) and reports the share of the other half it accepts (mean, and p10 to p90 over splits),"
           " the held-out agreement on accepted questions, and how often that fell below the target.", ""]
    for t in TARGETS:
        k = int(round(100 * t))
        md += [f"**Target {k}% agreement**", "",
               table(sorted(pooled, key=lambda r: -r[f"ltt_cov_{k}"]),
                     ["model", lambda r: fmt(r[f"oracle_cov_{k}"]), lambda r: fmt(r[f"ltt_cov_{k}"]),
                      lambda r: f"{fmt(r[f'ltt_cov_{k}_p10'])} to {fmt(r[f'ltt_cov_{k}_p90'])}",
                      lambda r: fmt(r[f"ltt_agreement_{k}"]), lambda r: fmt(r[f"ltt_violation_{k}"])],
                     ["model", "oracle coverage", "LTT coverage", "LTT p10 to p90", "held-out agreement",
                      "below target"]), ""]

    # 2. Same questions for every model.
    md += ["## 2. Same questions for every model", "",
           "Workflow paths differ by model, so section 1 compares slightly different question sets. Here each"
           " workflow is restricted to the question instances that all nine runs answered.", ""]
    common_rows, common_keys = [], {}
    for name, wf in workflows.items():
        keysets = [{a.key for a in wf.answers if a.model == m and a.kind in KINDS} for m in wf.models]
        common_keys[name] = set.intersection(*keysets)
        for m in wf.models:
            sel = [a for a in wf.answers if a.model == m and a.key in common_keys[name]]
            common_rows.append({"workflow": name, "model": m, **summarize(sel, splits=0)})
    pooled_common = []
    for m in models:
        sel = [a for a in by_model[m] if a.key in common_keys[a.workflow]]
        pooled_common.append({"model": m, **summarize(sel, splits=0)})
    write_csv(OUT / "common_questions.csv", common_rows)
    md += [table(sorted(pooled_common, key=lambda r: r["ece"]),
                 ["model", "n", lambda r: fmt(r["agreement"]), lambda r: fmt(r["mean_confidence"]),
                  lambda r: fmt(r["ece"], False), lambda r: fmt(r["oracle_cov_98"])],
                 ["model", "questions", "agreement", "mean conf.", "ECE", "oracle cov. @98%"]), ""]

    # 3. Reliability tables.
    md += ["## 3. Reliability (pooled)", ""]
    rel_rows = []
    for m in models:
        c = [a.confidence for a in by_model[m]]
        y = [a.agrees() for a in by_model[m]]
        for r in reliability(c, y):
            rel_rows.append({"model": m, **r})
    write_csv(OUT / "reliability.csv", rel_rows)
    for m in models:
        rs = [r for r in rel_rows if r["model"] == m]
        md += [f"**{m}**", "", table(rs, [lambda r: f"[{r['lo']:.2f}, {r['hi']:.2f}{']' if r['hi'] == 1 else ')'}",
                                          "n", lambda r: fmt(r["confidence"]), lambda r: fmt(r["agreement"])],
                                     ["confidence bin", "n", "mean confidence", "agreement"]), ""]

    # 4. Which reference family does each model lean toward?
    md += ["## 4. Reference family", "",
           "Agreement with each single reference model; how confident each model is on the questions where the two"
           " reference models disagree (contested questions); and agreement on the subset where they agree.", ""]
    fam = []
    for m in models:
        ans = by_model[m]
        clean = [a for a in ans if a.refs["openai"] == a.refs["anthropic"]]
        contested = [a for a in ans if a.refs["openai"] != a.refs["anthropic"]]
        fam.append({"model": m,
                    "vs_openai_ref": np.mean([a.agrees("openai") for a in ans]),
                    "vs_anthropic_ref": np.mean([a.agrees("anthropic") for a in ans]),
                    "lean_openai_minus_anthropic": np.mean([a.agrees("openai") for a in ans])
                    - np.mean([a.agrees("anthropic") for a in ans]),
                    "refs_disagree_n": len(contested),
                    "conf_where_refs_disagree": np.mean([a.confidence for a in contested]),
                    "share_ge_099_where_refs_disagree": np.mean([a.confidence >= 0.99 for a in contested]),
                    "refs_agree_n": len(clean),
                    "agreement_where_refs_agree": np.mean([a.agrees() for a in clean]),
                    "ece_where_refs_agree": ece([a.confidence for a in clean], [a.agrees() for a in clean]),
                    "cov98_where_refs_agree": coverage_at([a.confidence for a in clean], [a.agrees() for a in clean], 0.98)})
    write_csv(OUT / "reference_family.csv", fam)
    md += [table(fam, ["model", lambda r: fmt(r["vs_openai_ref"]), lambda r: fmt(r["vs_anthropic_ref"]),
                       lambda r: f"{100 * r['lean_openai_minus_anthropic']:+.1f} pts", "refs_disagree_n",
                       lambda r: fmt(r["conf_where_refs_disagree"]), lambda r: fmt(r["share_ge_099_where_refs_disagree"]),
                       "refs_agree_n",
                       lambda r: fmt(r["agreement_where_refs_agree"]), lambda r: fmt(r["ece_where_refs_agree"], False),
                       lambda r: fmt(r["cov98_where_refs_agree"])],
                 ["model", "vs OpenAI ref", "vs Anthropic ref", "lean", "questions (refs disagree)",
                  "mean conf. (refs disagree)", "conf. >= 0.99 (refs disagree)", "questions (refs agree)",
                  "agreement (refs agree)", "ECE (refs agree)", "oracle cov. @98% (refs agree)"]), ""]

    # 5. Case-level gate: escalate a case when its least confident answer is below a threshold.
    md += ["## 5. Case-level gate (in-sample only)", "",
           "Each case is auto-processed only if the lowest confidence among the model's answers in that case"
           " (all question types) clears a threshold. A case is right when the workflow's headline metric"
           " (exact action set, or primary action for agent traces) matches the consensus label for every"
           " policy. `auto@90` / `auto@95` are the largest shares of cases that can be auto-processed while the"
           " auto-processed cases stay >= 90% / 95% right. With 111-240 cases per workflow these are in-sample"
           " numbers; a held-out guarantee would need more cases.", ""]
    gate_rows = []
    for name, wf in workflows.items():
        for m in wf.models:
            ids, gate, ok = case_gate(wf, m)
            gate_rows.append({"workflow": name, "model": m, "cases": len(ids), "case_accuracy": ok.mean(),
                              "auto_at_90": coverage_at(gate, ok, 0.90), "auto_at_95": coverage_at(gate, ok, 0.95)})
    write_csv(OUT / "case_gate.csv", gate_rows)
    for name in workflows:
        rs = sorted([r for r in gate_rows if r["workflow"] == name], key=lambda r: (-r["auto_at_90"], -r["auto_at_95"]))
        md += [f"**{name}**", "", table(rs, ["model", "cases", lambda r: fmt(r["case_accuracy"]),
                                              lambda r: fmt(r["auto_at_90"]), lambda r: fmt(r["auto_at_95"])],
                                        ["model", "cases", "case accuracy", "auto@90", "auto@95"]), ""]

    # 6. Per workflow question-level summary.
    md += ["## 6. Per workflow (question level)", ""]
    per = []
    for name, wf in workflows.items():
        for m in wf.models:
            sel = [a for a in wf.answers if a.model == m and a.kind in KINDS]
            per.append({"workflow": name, "model": m, **summarize(sel, splits=0)})
    write_csv(OUT / "per_workflow.csv", per)
    for name in workflows:
        rs = sorted([r for r in per if r["workflow"] == name], key=lambda r: r["ece"])
        md += [f"**{name}**", "", table(rs, ["model", "n", lambda r: fmt(r["agreement"]),
                                              lambda r: fmt(r["mean_confidence"]), lambda r: fmt(r["ece"], False),
                                              lambda r: fmt(r["top_tie_share"]), lambda r: fmt(r["oracle_cov_98"])],
                                        ["model", "questions", "agreement", "mean conf.", "ECE", "top tie",
                                         "oracle cov. @98%"]), ""]

    (OUT / "RESULTS.md").write_text("\n".join(md))
    print("\n".join(md[:40]))
    print(f"\nWrote {OUT / 'RESULTS.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
